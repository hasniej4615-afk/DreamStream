/**
 * Intelligent Cinema Subtitle Translation Service.
 * - JIT (Just-In-Time) Progressive Streaming: translates the opening cues in ~300ms for 0s instant playback.
 * - Tag & SFX Isolation: masks HTML (<i>, <font>), musical notations (♪, ♫), and sound brackets ([laughter], (whispers))
 *   so formatting and sound descriptions are never mangled by translation engines.
 * - Cinema Subtitle Polishing: transforms stiff literal machine translations into natural cinema dialogue.
 * - Multi-Engine Failover: 5 redundant mobile & web gateways + MyMemory API fallback.
 * - Persistent disk caching in filesDir with corruption validation & LRU memory cache.
 */
object SubtitleTranslator {
    private const val TAG = "SubtitleTranslator"

    private const val BATCH_SIZE = 30
    private const val CONCURRENT_WORKERS = 6
    private const val BROWSER_UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36"
    private const val MOBILE_TRANSLATE_UA = "GoogleTranslate/6.28.0.05.421483610 (Linux; U; Android 13; Pixel 7)"

    // In-memory cache for ultra-fast (0ms) re-selection of translated subtitles
    private val memoryCache = LruCache<String, Pair<File, List<ParsedSubtitleCue>>>(10)

    // Dedicated high-speed OkHttpClient with HTTP/2 connection multiplexing and keep-alive
    private val translationHttpClient: OkHttpClient by lazy {
        OkHttpClient.Builder()
            .dispatcher(okhttp3.Dispatcher().apply {
                maxRequests = 64
                maxRequestsPerHost = 16
            })
            .connectionPool(okhttp3.ConnectionPool(16, 5, TimeUnit.MINUTES))
            .connectTimeout(8, TimeUnit.SECONDS)
            .readTimeout(12, TimeUnit.SECONDS)
            .writeTimeout(8, TimeUnit.SECONDS)
            .retryOnConnectionFailure(true)
            .protocols(listOf(okhttp3.Protocol.HTTP_2, okhttp3.Protocol.HTTP_1_1))
            .build()
    }

    fun getTranslatedSubtitlesDirectory(context: Context): File {
        val dir = File(context.filesDir, "translated_subtitles")
        if (!dir.exists()) dir.mkdirs()
        return dir
    }

    fun getTranslatedSubtitleFile(context: Context, videoId: String, targetLang: String): File {
        val cleanVid = videoId.replace(Regex("""[^a-zA-Z0-9_-]"""), "_").take(60)
        val targetCode = getLanguageCode(targetLang)
        return File(getTranslatedSubtitlesDirectory(context), "trans_${cleanVid}_${targetCode}.vtt")
    }

    fun getTranslatedSubtitlesForVideo(context: Context, videoId: String): List<Subtitle> {
        if (videoId.isBlank()) return emptyList()
        val cleanVid = videoId.replace(Regex("""[^a-zA-Z0-9_-]"""), "_").take(60)
        val prefix = "trans_${cleanVid}_"
        val dir = getTranslatedSubtitlesDirectory(context)
        val files = dir.listFiles { f ->
            f.isFile && f.name.startsWith(prefix) && f.name.endsWith(".vtt") && f.length() > 0L
        } ?: return emptyList()

        return files.sortedByDescending { it.lastModified() }.mapNotNull { file ->
            try {
                val targetCode = file.nameWithoutExtension.removePrefix(prefix)
                val langName = getLanguageDisplayName(targetCode)
                Subtitle(
                    label = "[AI Translated] $langName",
                    url = "file://${file.absolutePath}",
                    language = langName,
                    isAutoGenerated = true,
                    localUri = "file://${file.absolutePath}"
                )
            } catch (e: Exception) {
                null
            }
        }
    }

    fun deleteTranslatedSubtitleByUrl(url: String): Boolean {
        return try {
            val filePath = if (url.startsWith("file://")) url.removePrefix("file://") else url
            val file = File(filePath)
            if (file.exists()) {
                val deleted = file.delete()
                Log.i(TAG, "Deleted translated subtitle file: $filePath (success: $deleted)")
                deleted
            } else {
                false
            }
        } catch (e: Exception) {
            Log.e(TAG, "Failed to delete subtitle: $url", e)
            false
        }
    }

    fun enforceStorageQuota(context: Context, maxFiles: Int = 50) {
        try {
            val dir = getTranslatedSubtitlesDirectory(context)
            val files = dir.listFiles { f -> f.isFile && f.name.endsWith(".vtt") } ?: return
            if (files.size > maxFiles) {
                val toDelete = files.sortedBy { it.lastModified() }.take(files.size - maxFiles)
                for (f in toDelete) {
                    Log.i(TAG, "Enforcing storage quota: deleting old translated subtitle ${f.name}")
                    f.delete()
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Failed to enforce storage quota", e)
        }
    }

    fun getLanguageCode(lang: String): String {
        val low = lang.lowercase().trim()
        return when {
            low.contains("indonesi") || low == "id" || low == "ind" -> "id"
            low.contains("malay") || low.contains("melayu") || low == "ms" || low == "msa" -> "ms"
            low.contains("english") || low == "en" || low == "eng" -> "en"
            low.contains("japan") || low == "ja" || low == "jpn" -> "ja"
            low.contains("korean") || low == "ko" || low == "kor" -> "ko"
            low.contains("chinese") || low == "zh" || low == "chi" -> "zh-CN"
            low.contains("thai") || low == "th" || low == "tha" -> "th"
            low.contains("arabic") || low == "ar" || low == "ara" -> "ar"
            low.contains("spanish") || low == "es" || low == "spa" -> "es"
            low.contains("french") || low == "fr" || low == "fre" -> "fr"
            low.contains("german") || low == "de" || low == "ger" -> "de"
            else -> "id"
        }
    }

    fun getLanguageDisplayName(codeOrName: String): String {
        val code = getLanguageCode(codeOrName)
        return when (code) {
            "id" -> "Indonesian"
            "ms" -> "Malay"
            "en" -> "English"
            "ja" -> "Japanese"
            "ko" -> "Korean"
            "zh-CN" -> "Chinese"
            "th" -> "Thai"
            "ar" -> "Arabic"
            "es" -> "Spanish"
            "fr" -> "French"
            "de" -> "German"
            else -> code.uppercase()
        }
    }

    suspend fun translateCues(
        context: Context,
        cues: List<ParsedSubtitleCue>,
        title: String,
        targetLang: String = "id",
        videoId: String? = null,
        onProgress: ((Int, Int) -> Unit)? = null,
        onBatchCompleted: ((batchIndex: Int, translatedBatch: List<ParsedSubtitleCue>) -> Unit)? = null
    ): Pair<File, List<ParsedSubtitleCue>>? = withContext(Dispatchers.IO) {
        if (cues.isEmpty()) return@withContext null
        val targetCode = getLanguageCode(targetLang)
        val cleanTitle = title.replace(Regex("""[^a-zA-Z0-9]"""), "_").ifBlank { "video" }.take(30)
        val cueHash = (cues.size.toString() + "_" + cues.take(5).joinToString("") { it.text } + "_" + cues.takeLast(5).joinToString("") { it.text }).hashCode().let { Integer.toHexString(it) }

        val cachedFile = if (!videoId.isNullOrBlank()) {
            getTranslatedSubtitleFile(context, videoId, targetCode)
        } else {
            File(getTranslatedSubtitlesDirectory(context), "trans_${cleanTitle}_${cueHash}_${targetCode}.vtt")
        }
        val cacheKey = cachedFile.nameWithoutExtension

        // 1. Check in-memory LRU cache (0ms instant return)
        synchronized(memoryCache) {
            val memCached = memoryCache.get(cacheKey)
            if (memCached != null && memCached.first.exists() && memCached.first.length() > 0L) {
                Log.i(TAG, "Loaded in-memory cached translation: $cacheKey (${memCached.second.size} cues)")
                return@withContext memCached
            }
        }

        // 2. Check persistent disk cache with corruption validation
        if (cachedFile.exists() && cachedFile.length() > 0L) {
            val parsed = SubtitleParser.parse(cachedFile)
            val isCorruptedCache = if (targetCode != "en" && cues.isNotEmpty() && parsed.isNotEmpty()) {
                val sampleOriginal = cues.filter { it.text.isNotBlank() }.take(5).map { it.text.trim() }
                val sampleParsed = parsed.filter { it.text.isNotBlank() }.take(5).map { it.text.trim() }
                sampleOriginal == sampleParsed
            } else false

            if (isCorruptedCache) {
                Log.w(TAG, "Detected corrupted/untranslated cached subtitle (${cachedFile.name}), deleting and re-translating")
                cachedFile.delete()
            } else if (parsed.isNotEmpty()) {
                Log.i(TAG, "Loaded cached translation from disk: ${cachedFile.absolutePath} (${parsed.size} cues)")
                cachedFile.setLastModified(System.currentTimeMillis())
                val pair = Pair(cachedFile, parsed)
                synchronized(memoryCache) {
                    memoryCache.put(cacheKey, pair)
                }
                return@withContext pair
            }
        }

        // 3. JIT Priority Streaming: Translate Batch 0 immediately to unlock 0-second playback display
        val chunks = cues.chunked(BATCH_SIZE)
        val total = chunks.size
        val semaphore = Semaphore(CONCURRENT_WORKERS)
        val completedCount = AtomicInteger(0)
        onProgress?.invoke(0, total)

        val orderedResults = ConcurrentHashMap<Int, List<ParsedSubtitleCue>>()

        // Immediate Batch 0 translation (~300ms)
        if (chunks.isNotEmpty()) {
            val batch0 = translateBatch(chunks[0], targetCode)
            orderedResults[0] = batch0
            completedCount.incrementAndGet()
            onProgress?.invoke(1, total)
            onBatchCompleted?.invoke(0, batch0)
            Log.i(TAG, "⚡ JIT Immediate Batch 0 delivered: ${batch0.size} cues ready for instant display")
        }

        // Concurrent background execution for chunks 1..N
        if (chunks.size > 1) {
            coroutineScope {
                val remainingDeferreds = (1 until chunks.size).map { index ->
                    async(Dispatchers.IO) {
                        semaphore.withPermit {
                            val translatedBatch = translateBatch(chunks[index], targetCode)
                            orderedResults[index] = translatedBatch
                            val cur = completedCount.incrementAndGet()
                            onProgress?.invoke(cur, total)
                            onBatchCompleted?.invoke(index, translatedBatch)
                        }
                    }
                }
                remainingDeferreds.awaitAll()
            }
        }

        val translatedCues = ArrayList<ParsedSubtitleCue>(cues.size)
        for (i in chunks.indices) {
            val batch = orderedResults[i] ?: chunks[i]
            translatedCues.addAll(batch)
        }

        if (translatedCues.isEmpty()) return@withContext null

        // Integrity check: Verify result is not untouched original text across a sample of non-blank cues
        if (targetCode != "en") {
            val nonBlankOrig = cues.filter { it.text.isNotBlank() }
            val nonBlankTrans = translatedCues.filter { it.text.isNotBlank() }
            if (nonBlankOrig.size >= 8 && nonBlankTrans.size >= 8) {
                val sampleOrig = nonBlankOrig.drop(2).take(15).map { it.text.trim() }
                val sampleTrans = nonBlankTrans.drop(2).take(15).map { it.text.trim() }
                if (sampleOrig.isNotEmpty() && sampleOrig == sampleTrans) {
                    Log.e(TAG, "Translation failed: sample results are identical to original text. Discarding bad result.")
                    return@withContext null
                }
            }
        }

        val resultPair = Pair(cachedFile, translatedCues)
        try {
            val vttContent = SubtitleParser.toWebVtt(translatedCues)
            cachedFile.writeText(vttContent, Charsets.UTF_8)
            cachedFile.setLastModified(System.currentTimeMillis())
            enforceStorageQuota(context, 50)
            Log.i(TAG, "Translation completed and cached: ${cachedFile.absolutePath} (${translatedCues.size} cues)")
        } catch (e: Exception) {
            Log.e(TAG, "Failed to cache translated subtitle to disk", e)
        }

        synchronized(memoryCache) {
            memoryCache.put(cacheKey, resultPair)
        }

        resultPair
    }

    private data class MaskedCue(
        val originalCue: ParsedSubtitleCue,
        val maskedText: String,
        val tokenMap: Map<String, String>
    )

    private fun maskCue(cue: ParsedSubtitleCue): MaskedCue {
        val tokenMap = mutableMapOf<String, String>()
        var tokenIdx = 0
        var text = cue.text

        // 1. Mask HTML formatting tags (<i>, </i>, <b>, <font>, etc.)
        text = Regex("""<[^>]+>""").replace(text) { match ->
            val token = "⟦T${tokenIdx++}⟧"
            tokenMap[token] = match.value
            token
        }

        // 2. Mask musical notation symbols (♪, ♫)
        text = Regex("""[♪♫]""").replace(text) { match ->
            val token = "⟦M${tokenIdx++}⟧"
            tokenMap[token] = match.value
            token
        }

        // 3. Mask bracketed sound descriptions: [screams], (sighs), [door opens], [man's voice]
        text = Regex("""(?:\[|\()([A-Za-z0-9\s,'!?.–-]{2,45})(?:\]|\))""").replace(text) { match ->
            val token = "⟦S${tokenIdx++}⟧"
            tokenMap[token] = match.value
            token
        }

        return MaskedCue(cue, text, tokenMap)
    }

    private fun unmaskText(rawTranslated: String, tokenMap: Map<String, String>, targetCode: String): String {
        var restored = rawTranslated
        for ((token, original) in tokenMap) {
            val cleanKey = token.trim('⟦', '⟧')
            val regex = Regex("""(?i)⟦\s*$cleanKey\s*⟧|\[\s*$cleanKey\s*\]|【\s*$cleanKey\s*】|［\s*$cleanKey\s*］""")
            restored = regex.replace(restored, original)
        }
        val formatted = restoreFormatting(restored)
        return CinemaSubtitlePolisher.polish(formatted, targetCode)
    }

    private fun translateBatch(
        chunk: List<ParsedSubtitleCue>,
        targetCode: String
    ): List<ParsedSubtitleCue> {
        if (chunk.isEmpty()) return emptyList()
        if (chunk.all { it.text.isBlank() }) return chunk

        val maskedCues = chunk.map { maskCue(it) }
        val delimiter = " [|||] "
        val joinedText = maskedCues.joinToString(delimiter) { it.maskedText.replace("\n", " <br> ") }

        try {
            val translatedRaw = translateText(joinedText, targetCode)
            if (translatedRaw != null) {
                val splitRegex = Regex("""\s*(?:\[\s*[|｜]{1,3}\s*\]|【\s*[|｜]{1,3}\s*】|［\s*[|｜]{1,3}\s*］|\]\s*[|｜]{1,3}\s*\[)\s*""")
                val parts = translatedRaw.split(splitRegex)
                if (parts.size == chunk.size) {
                    return chunk.mapIndexed { idx, cue ->
                        val unmasked = unmaskText(parts[idx], maskedCues[idx].tokenMap, targetCode)
                        cue.copy(text = unmasked)
                    }
                } else if (parts.size > 1) {
                    Log.w(TAG, "Batch split count mismatch (got ${parts.size}, expected ${chunk.size})")
                    if (chunk.size > 4) {
                        val mid = chunk.size / 2
                        val left = translateBatch(chunk.subList(0, mid), targetCode)
                        val right = translateBatch(chunk.subList(mid, chunk.size), targetCode)
                        return left + right
                    } else {
                        return chunk.mapIndexed { idx, cue ->
                            val text = if (idx < parts.size) unmaskText(parts[idx], maskedCues[idx].tokenMap, targetCode)
                                       else (translateText(cue.text, targetCode)?.let { restoreFormatting(it) } ?: cue.text)
                            cue.copy(text = text)
                        }
                    }
                }
            }
        } catch (e: Exception) {
            Log.w(TAG, "Batch translation failed, attempting binary split", e)
        }

        // Binary split fallback for fast recovery
        if (chunk.size > 4) {
            val mid = chunk.size / 2
            val left = translateBatch(chunk.subList(0, mid), targetCode)
            val right = translateBatch(chunk.subList(mid, chunk.size), targetCode)
            return left + right
        }

        // Terminal fallback for tiny chunks (<= 4 cues)
        return chunk.map { cue ->
            if (cue.text.isBlank()) cue
            else {
                val masked = maskCue(cue)
                val singleTrans = translateText(masked.maskedText, targetCode)
                if (singleTrans != null && singleTrans.isNotBlank()) {
                    val unmasked = unmaskText(singleTrans, masked.tokenMap, targetCode)
                    cue.copy(text = unmasked)
                } else {
                    cue
                }
            }
        }
    }

    private fun restoreFormatting(raw: String): String {
        return raw.replace(Regex("(?i)<br\\s*/?>"), "\n")
            .replace(Regex("""(?i)&lt;br\s*/?&gt;"""), "\n")
            .replace(" --NL-- ", "\n")
            .replace("--NL--", "\n")
            .replace("&amp;", "&")
            .replace("&lt;", "<")
            .replace("&gt;", ">")
            .replace("&quot;", "\"")
            .replace("&#39;", "'")
            .replace("&apos;", "'")
            .replace("&nbsp;", " ")
            .trim()
    }

    /**
     * Resilient Multi-Engine Translation Gateway.
     * Tries 5 Google Mobile/Web endpoints with graceful fallback to MyMemory API.
     */
    fun translateText(text: String, targetCode: String): String? {
        if (text.isBlank()) return text

        val endpoints = listOf(
            "https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=$targetCode&dt=t",
            "https://translate.google.com/translate_a/single?client=gtx&sl=auto&tl=$targetCode&dt=t",
            "https://clients5.google.com/translate_a/t?client=dict-chrome-ex&sl=auto&tl=$targetCode",
            "https://translate.googleapis.com/translate_a/single?client=it&sl=auto&tl=$targetCode&dt=t",
            "https://translate.googleapis.com/translate_a/t?client=at&sl=auto&tl=$targetCode"
        )

        for (endpoint in endpoints) {
            try {
                val formBody = FormBody.Builder()
                    .add("q", text)
                    .build()

                val request = Request.Builder()
                    .url(endpoint)
                    .header("User-Agent", BROWSER_UA)
                    .header("Accept", "*/*")
                    .post(formBody)
                    .build()

                val result = translationHttpClient.newCall(request).execute().use { response ->
                    if (!response.isSuccessful) {
                        return@use null
                    }
                    val bodyStr = response.body?.string() ?: return@use null
                    if (bodyStr.isBlank()) return@use null

                    val jsonArray = JSONArray(bodyStr)
                    val sb = StringBuilder()
                    if (endpoint.contains("/translate_a/t?")) {
                        val firstItem = jsonArray.opt(0)
                        if (firstItem is JSONArray) {
                            for (j in 0 until firstItem.length()) {
                                sb.append(firstItem.optString(j))
                                break
                            }
                        } else if (firstItem is String) {
                            sb.append(firstItem)
                        }
                    } else {
                        val sentences = jsonArray.optJSONArray(0)
                        if (sentences != null) {
                            for (i in 0 until sentences.length()) {
                                val item = sentences.optJSONArray(i)
                                if (item != null) {
                                    sb.append(item.optString(0))
                                }
                            }
                        }
                    }
                    sb.toString()
                }

                if (!result.isNullOrBlank()) {
                    return result
                }
            } catch (e: Exception) {
                // Try next gateway
            }
        }

        // Secondary Failover: MyMemory API (for high-traffic or Google temporary blocks)
        try {
            val delimiter = " [|||] "
            val parts = if (text.contains(delimiter)) text.split(delimiter) else listOf(text)
            val chunkedParts = parts.chunked(6)
            val memoryResults = mutableListOf<String>()
            var myMemSuccess = true

            for (group in chunkedParts) {
                val groupText = group.joinToString(delimiter)
                val encText = URLEncoder.encode(groupText.take(900), "UTF-8")
                val myMemUrl = "https://api.mymemory.translated.net/get?q=$encText&langpair=auto|$targetCode"
                val req = Request.Builder()
                    .url(myMemUrl)
                    .header("User-Agent", BROWSER_UA)
                    .get()
                    .build()

                val part = translationHttpClient.newCall(req).execute().use { resp ->
                    if (resp.isSuccessful) {
                        val body = resp.body?.string()
                        if (!body.isNullOrBlank()) {
                            val jsonObj = JSONObject(body)
                            val match = jsonObj.optJSONObject("responseData")?.optString("translatedText")
                            if (!match.isNullOrBlank() && !match.startsWith("MYMEMORY WARNING")) {
                                match
                            } else null
                        } else null
                    } else null
                }

                if (part != null) {
                    memoryResults.add(part)
                } else {
                    myMemSuccess = false
                    break
                }
            }

            if (myMemSuccess && memoryResults.isNotEmpty()) {
                return memoryResults.joinToString(delimiter)
            }
        } catch (_: Exception) {}

        return null
    }

    /**
     * Local Cinema Dialogue & Subtitle Polisher.
     * Replaces awkward literal machine-translations with natural cinema idioms.
     */
    object CinemaSubtitlePolisher {
        private val indonesianReplacements = listOf(
            Regex("""(?i)\b(?:beri|berikan)\s+aku\s+istirahat\b""") to "yang benar saja",
            Regex("""(?i)\bapa-apaan\s+itu\b""") to "apa-apaan ini",
            Regex("""(?i)\btidak\s+mungkin\s+sekali\b""") to "mustahil",
            Regex("""(?i)\bjangan\s+khawatir\s+tentang\s+hal\s+itu\b""") to "tenang saja",
            Regex("""(?i)\bapa\s+yang\s+kamu\s+bicarakan\b""") to "bicara apa kamu",
            Regex("""(?i)\bkeluar\s+dari\s+sini\b""") to "pergi dari sini",
            Regex("""(?i)\btetap\s+di\s+sana\b""") to "tetap di situ",
            Regex("""(?i)\bperhatikan\s+langkahmu\b""") to "hati-hati",
            Regex("""(?i)\bada\s+apa\s+denganmu\b""") to "kamu kenapa",
            Regex("""(?i)\bkamu\s+bercanda\b""") to "bercanda ya",
            Regex("""(?i)\bawas\s+saja\b""") to "awas",
            Regex("""(?i)\bsudah\s+waktunya\b""") to "saatnya",
            Regex("""(?i)\baku\s+bersumpah\s+demi\s+tuhan\b""") to "sumpah",
            Regex("""(?i)\bpegang\s+tanganku\b""") to "genggam tanganku"
        )

        fun polish(text: String, targetLangCode: String): String {
            if (targetLangCode != "id" && targetLangCode != "ms") return text
            var res = text
            for ((regex, replacement) in indonesianReplacements) {
                res = regex.replace(res, replacement)
            }
            return res
        }
    }
